"""Track 'lexical': build the OPTIONAL extra labelled pool.

5,229 rows of data_tickets.parquet carry language == "de" but are written in English. The project's split builder
keeps language == "en" only, so these rows are in neither train nor test. They are real labelled tickets of the same
dataset (not generated by us and not derived from validation/test tickets). This script writes the unique ones that
use the ten shared queues to data/x_lexical/extra_en_pool.jsonl.

Leak guards: (1) rows whose cleaned text equals a train-split text are dropped here; (2) at prediction time the final
module additionally drops any extra row that is an exact or near-exact (baseline TF-IDF cosine >= 0.95) copy of an
evaluation ticket, mirroring the guard in src/experiments/german_embeddings/add_german.py. The test split is never read here.
"""
import json
import pyarrow.parquet as pq
from common import ROOT, clean, load_meta, load_split

EN = set("the and to of is are for with this that our we you please have has been can could would your on in an it as be i my".split())
DE = set("der die das und ist sind für mit wir sie bitte haben hat wurde können könnten ihre ihr auf in ein eine es als ich mein nicht zu den dem des".split())


def looks_english(text):
    w = text.split(); e = sum(x in EN for x in w); d = sum(x in DE for x in w)
    return e > 2 * d


def main():
    l2i = load_meta()["label2id"]
    train_texts = set(load_split("train")[0])
    t = pq.read_table(ROOT / "data_tickets.parquet").to_pydict()
    seen, rows = set(), []
    for i in range(len(t["queue"])):
        if t["language"][i] != "de" or t["queue"][i] not in l2i:
            continue
        tx = clean(t["subject"][i], t["body"][i])
        if not tx or tx in seen or tx in train_texts or not looks_english(tx):
            continue
        seen.add(tx)
        rows.append({"text": tx, "label": l2i[t["queue"][i]], "type": t["type"][i], "priority": t["priority"][i]})
    out = ROOT / "data/x_lexical/extra_en_pool.jsonl"
    out.parent.mkdir(parents=True, exist_ok=True)
    with open(out, "w") as f:
        for r in rows:
            f.write(json.dumps(r) + "\n")
    print(f"wrote {len(rows)} rows to {out}")


if __name__ == "__main__":
    main()
